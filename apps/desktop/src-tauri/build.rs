use std::{env, fs, path::PathBuf};

const DEMO_KEYS: [(&str, &str); 4] = [
    ("groq", "GIVEMEJOB_GROQ_DEMO_KEY"),
    ("gemini", "GIVEMEJOB_GEMINI_DEMO_KEY"),
    ("openrouter", "GIVEMEJOB_OPENROUTER_DEMO_KEY"),
    ("cerebras", "GIVEMEJOB_CEREBRAS_DEMO_KEY"),
];

fn obfuscate(value: &[u8], provider_index: usize) -> Vec<u8> {
    value
        .iter()
        .enumerate()
        .map(|(index, byte)| {
            let mask = 0x5a_u8
                .wrapping_add((provider_index as u8).wrapping_mul(29))
                .wrapping_add((index as u8).wrapping_mul(17));
            byte ^ mask
        })
        .collect()
}

fn write_demo_keys() {
    let release_build = env::var("PROFILE").as_deref() == Ok("release");
    let mut generated = String::from(
        "// Generated by build.rs. Demo credentials remain intentionally extractable from a release binary.\n",
    );
    generated.push_str(&format!(
        "pub(crate) const DEMO_KEYS: [(&str, &[u8]); {}] = [\n",
        DEMO_KEYS.len()
    ));
    for (index, (provider, variable)) in DEMO_KEYS.iter().enumerate() {
        println!("cargo:rerun-if-env-changed={variable}");
        let encoded = if release_build {
            env::var(variable)
                .ok()
                .filter(|value| !value.trim().is_empty())
                .map(|value| obfuscate(value.as_bytes(), index))
                .unwrap_or_default()
        } else {
            Vec::new()
        };
        generated.push_str(&format!("    ({provider:?}, &{encoded:?}),\n"));
    }
    generated.push_str("];\n");

    let output =
        PathBuf::from(env::var_os("OUT_DIR").expect("Cargo provides OUT_DIR")).join("demo_keys.rs");
    fs::write(output, generated).expect("generated demo key module should be written");
}

fn main() {
    write_demo_keys();
    tauri_build::build()
}
