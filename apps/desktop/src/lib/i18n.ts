export type AppLocale = "ru" | "en";

const configuredLocale = productConfig.localization.uiDefaultLocale;
export const defaultLocale: AppLocale = configuredLocale === "en" ? "en" : "ru";

const localeTags: Readonly<Record<AppLocale, string>> = { en: "en-US", ru: "ru-RU" };
let activeLocale: AppLocale = defaultLocale;

export function getLocaleTag(locale: AppLocale = activeLocale): string {
  return localeTags[locale];
}

export function setActiveLocale(locale: AppLocale): void {
  activeLocale = locale;
  if (typeof document !== "undefined") document.documentElement.lang = locale;
}

export function getActiveLocale(): AppLocale {
  return activeLocale;
}

export function t(key: MessageKey, locale: AppLocale = activeLocale): string {
  return locale === "en" ? englishMessages[key] : messages.ru[key];
}
